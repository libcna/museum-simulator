#!/usr/bin/env bash
# Prints the museum's summary numbers (everything is measured or generated, nothing typed in): structure counts from the
# catalogue, source size, test counts, and the interactable counts from a quick tour. Used for the project report.
set -u
cd "$(dirname "$0")/.." || exit 2
bin=${MUSEUM_BIN:-${BUILD_DIR:-build}/bin/cna-3d-museum}
echo "== structure (from the catalogue)"
"$bin" --validate 2>/dev/null | sed -n 1,8p
echo
echo "== source"
cpp=$(find src tests -name '*.cpp' -o -name '*.hpp' | xargs cat | wc -l)
echo "C++ (src + tests): $cpp lines in $(find src tests -name '*.cpp' -o -name '*.hpp' | wc -l) files"
echo "scripts and generators: $(find tools -name '*.sh' -o -name '*.py' | xargs cat | wc -l) lines"
echo "content: $(du -sh Content | cut -f1) ($(find Content -type f | wc -l) files, all generated by tools/gen_*.py or compiled at build time)"
echo "reference images: $(du -sh tests/reference | cut -f1)"
echo
echo "== tests"
"${BUILD_DIR:-build}/bin/museum_tests" 2>&1 | head -1
echo
echo "== interactables (one tour)"
tools/tour.sh -f 2 2>&1 | grep -o "interactables.*"
